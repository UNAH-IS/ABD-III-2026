CREATE OR REPLACE PROCEDURE P_GUARDAR_EMPLEADO(
    PO_EMPLOYEE_ID OUT EMPLOYEES.EMPLOYEE_ID%TYPE, 
    PI_FIRST_NAME IN EMPLOYEES.FIRST_NAME%TYPE,
    PI_LAST_NAME IN EMPLOYEES.LAST_NAME%TYPE,
    PI_EMAIL EMPLOYEES.EMAIL%TYPE,
    PI_PHONE_NUMBER EMPLOYEES.PHONE_NUMBER%TYPE,
    PI_HIRE_DATE EMPLOYEES.HIRE_DATE%TYPE,
    PI_JOB_ID EMPLOYEES.JOB_ID%TYPE,
    PI_SALARY EMPLOYEES.SALARY%TYPE,
    PI_COMMISSION_PCT EMPLOYEES.COMMISSION_PCT%TYPE,
    PI_MANAGER_ID EMPLOYEES.MANAGER_ID%TYPE,
    PI_DEPARTMENT_ID EMPLOYEES.DEPARTMENT_ID%TYPE,
    PO_MENSAJE_RESULTADO OUT VARCHAR2,
    PO_CODIGO_RESULTADO OUT NUMBER
) IS
    V_CANTIDAD_DEPARTAMENTOS NUMBER;
    V_CANTIDAD_JOBS NUMBER;
    V_MIN_SALARY NUMBER;
    V_MAX_SALARY NUMBER;
    E_SALARIO_FUERA_RANGO EXCEPTION;
    E_DEPARTAMENTO_NO_EXISTE EXCEPTION;
    E_JOB_NO_EXISTE EXCEPTION;
    V_MANAGER_ID NUMBER;
    V_OPERACION NUMBER;
BEGIN
    SELECT COUNT(*)
    INTO V_CANTIDAD_DEPARTAMENTOS
    FROM DEPARTMENTS
    WHERE DEPARTMENT_ID = PI_DEPARTMENT_ID;

    IF (V_CANTIDAD_DEPARTAMENTOS = 0) THEN
        RAISE E_DEPARTAMENTO_NO_EXISTE;
    END IF;

    SELECT COUNT(*)
    INTO V_CANTIDAD_JOBS
    FROM JOBS
    WHERE JOB_ID = PI_JOB_ID;

    IF (V_CANTIDAD_JOBS = 0) THEN
        RAISE E_JOB_NO_EXISTE;
    END IF;

    SELECT MIN_SALARY, MAX_SALARY
    INTO V_MIN_SALARY, V_MAX_SALARY
    FROM JOBS
    WHERE JOB_ID = PI_JOB_ID;

    IF (PI_SALARY NOT BETWEEN V_MIN_SALARY AND V_MAX_SALARY) THEN
        RAISE E_SALARIO_FUERA_RANGO;
    END IF;


    SELECT EMPLOYEE_ID 
    INTO V_MANAGER_ID
    FROM EMPLOYEES
    WHERE EMPLOYEE_ID = PI_MANAGER_ID;

    V_OPERACION := 1/0; 

    PO_EMPLOYEE_ID := EMPLOYEES_SEQ.NEXTVAL;
    INSERT INTO EMPLOYEES (
        EMPLOYEE_ID,
        FIRST_NAME,
        LAST_NAME,
        EMAIL,
        PHONE_NUMBER,
        HIRE_DATE,
        JOB_ID,
        SALARY,
        COMMISSION_PCT,
        MANAGER_ID,
        DEPARTMENT_ID
   ) VALUES ( 
        PO_EMPLOYEE_ID,
        PI_FIRST_NAME,
        PI_LAST_NAME,
        PI_EMAIL,
        PI_PHONE_NUMBER,
        PI_HIRE_DATE,
        PI_JOB_ID,
        PI_SALARY,
        PI_COMMISSION_PCT,
        PI_MANAGER_ID,
        PI_DEPARTMENT_ID
   );

   COMMIT;

   PO_MENSAJE_RESULTADO := 'Registro insertado';
   PO_CODIGO_RESULTADO := 0; 
EXCEPTION
    WHEN E_SALARIO_FUERA_RANGO THEN
        PO_MENSAJE_RESULTADO := 'Salario fuera del rango permitido';
        PO_CODIGO_RESULTADO := 3;
    WHEN E_DEPARTAMENTO_NO_EXISTE THEN
        PO_MENSAJE_RESULTADO := 'Departamento con codigo ' || PI_DEPARTMENT_ID || ' NO EXISTE';
        PO_CODIGO_RESULTADO := 1;
    WHEN E_JOB_NO_EXISTE THEN
        PO_MENSAJE_RESULTADO := 'Job con codigo ' || PI_JOB_ID || ' NO EXISTE';
        PO_CODIGO_RESULTADO := 2;
    WHEN NO_DATA_FOUND THEN
        PO_MENSAJE_RESULTADO := 'No se encontró el registro ' || SQLCODE || ' - ' || SQLERRM;
        PO_CODIGO_RESULTADO := 4;
    -- WHEN TIPO_ERROR_2 THEN
    --     --GESTIONAR_ERROR
    WHEN OTHERS THEN 
        PO_MENSAJE_RESULTADO := 'Ocurrió un error inesperado ' || SQLCODE || ' - ' || SQLERRM;
        PO_CODIGO_RESULTADO := 5;
END;


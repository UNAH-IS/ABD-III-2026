    V_EMPLOYEE EMPLOYEES%ROWTYPE;
BEGIN 
    OPEN C_EMPLOYEES; -- SE EJECUTA LA INSTRUCCION SELECT
    LOOP
        FETCH C_EMPLOYEES INTO V_EMPLOYEE;
        EXIT WHEN C_EMPLOYEES%NOTFOUND;
        DBMS_OUTPUT.PUT_LINE('Empleado obtenido: ' || V_EMPLOYEE.FIRST_NAME || ' ' || V_EMPLOYEE.LAST_NAME);
    END LOOP;

    CLOSE C_EMPLOYEES;
END;



